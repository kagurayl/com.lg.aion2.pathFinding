function HexRGB(hex)
    --local num = tonumber(hex, 16)
    local r = bit.band(bit.rshift(hex, 16), 255)
    local g = bit.band(bit.rshift(hex, 8), 255)
    local b = bit.band((hex), 255)
    return r / 255.0, g / 255.0, b /255.0
end

function HexRGBDefault(hex)
    if hex ~= nil then
        return HexRGB(hex)
    else
        return 1.0, 1.0, 1.0
    end
end

function HexRGBA(hex)
    local r = bit.band(bit.rshift(hex, 24), 255)
    local g = bit.band(bit.rshift(hex, 16), 255)
    local b = bit.band(bit.rshift(hex, 8), 255)
    local a = bit.band((hex), 255)
    return r / 255.0, g / 255.0, b /255.0, a / 255.0
end

function ToHex(r, g, b)
    local byter = math.tocolorbyte(r)
    local byteg = math.tocolorbyte(g)
    local byteb = math.tocolorbyte(b)
    return bit.bor(bit.lshift(byter, 16), bit.lshift(byteg, 8), byteb)
end

function ToHexRGBA(r, g, b, a)
    local byter = math.tocolorbyte(r)
    local byteg = math.tocolorbyte(g)
    local byteb = math.tocolorbyte(b)
    local bytea = math.tocolorbyte(a)
    return bit.bor(bit.lshift(bytea, 24), bit.lshift(byter, 16), bit.lshift(byteg, 8), byteb)
end

