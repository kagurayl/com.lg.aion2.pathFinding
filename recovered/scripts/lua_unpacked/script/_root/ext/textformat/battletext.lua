local function battletext_addbufftext(key, text)
    local addbuff = {}
    addbuff.a_to_me = string.format("STR_SKILL_SUCC_%s_A_TO_ME", text)
    addbuff.a_to_b = string.format("STR_SKILL_SUCC_%s_A_TO_B", text)
    addbuff.a_to_self = string.format("STR_SKILL_SUCC_%s_A_TO_SELF", text)
    addbuff.me_to_self = string.format("STR_SKILL_SUCC_%s_ME_TO_SELF", text)
    addbuff.me_to_b = string.format("STR_SKILL_SUCC_%s_ME_TO_B", text)
    local removebuff = {}
    removebuff.a = string.format("STR_SKILL_SUCC_%s_END_A", text)
    removebuff.a_to_me = string.format("STR_SKILL_SUCC_%s_END_A_TO_ME", text)
    removebuff.a_to_b = string.format("STR_SKILL_SUCC_%s_END_A_TO_B", text)
    removebuff.a_to_self = string.format("STR_SKILL_SUCC_%s_END_A_TO_SELF", text)
    removebuff.me = string.format("STR_SKILL_SUCC_%s_END_ME", text)
    removebuff.me_to_self = string.format("STR_SKILL_SUCC_%s_END_ME_TO_SELF", text)
    removebuff.me_to_b = string.format("STR_SKILL_SUCC_%s_END_ME_TO_B", text)
    battletext_buffkey[key] = {add = addbuff, remove = removebuff}
end

