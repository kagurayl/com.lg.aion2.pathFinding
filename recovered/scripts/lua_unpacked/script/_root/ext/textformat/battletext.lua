function battletext_setinfo(textchattype, textbattletype, target, attackerid, protectorid, skillid)
    m_battletext_chattype = textchattype + textbattletype
    m_battletext_target = target
    m_battletext_attackerid = attackerid
    m_battletext_protectorid = protectorid
    m_battletext_skillid = skillid
end

function battletext_addtextformat(textkey, num0, num1, num2, num3, headtext)
    if not c_textkey(textkey) then
        return
    end
    local desc = textformat_gettext(c_textformat(textkey), function(key)
        if key == "SkillName" then
            local config_skill = csvskill_getfromid(m_battletext_skillid)
            if config_skill ~= nil then
                return config_skill.name
            end
        elseif key == "SkillCaster" then
            local attacker = actormanager_getfromactorid(m_battletext_attackerid)
            if attacker ~= nil then
                return attacker.attr.name
            end
        elseif key == "SkillTarget" then
            return m_battletext_target.attr.name
        elseif key == "Protector" then
            local protector = actormanager_getfromactorid(m_battletext_protectorid)
            if protector ~= nil then
                return protector.attr.name
            end
        elseif key == "num0" or key == 0 then
            return num0
        elseif key == "num1" or key == 1 then
            return num1
        elseif key == "num2" or key == 2 then
            return num2
        elseif key == "num3" or key == 3 then
            return num3
        end
    end)
    if #desc > 0 then
        if headtext ~= nil then
            desc = headtext .. desc
        end
        chat_addsimple(m_battletext_chattype, desc)
    end
end

function battletext_addtextformatex(a_to_me, a_to_b, a_to_self, me_to_self, me_to_b, num0, num1, num2, num3, headtext)
    if m_battletext_target:isme() then
        if m_battletext_target.actorid == m_battletext_attackerid then
            battletext_addtextformat(me_to_self, num0, num1, num2, num3, headtext)
        else
            battletext_addtextformat(a_to_me, num0, num1, num2, num3, headtext)
        end
    elseif m_battletext_attackerid == playerattr_info.actorid then
        battletext_addtextformat(me_to_b, num0, num1, num2, num3, headtext)
    else
        if m_battletext_target.actorid == m_battletext_attackerid then
            battletext_addtextformat(a_to_self, num0, num1, num2, num3, headtext)
        else
            battletext_addtextformat(a_to_b, num0, num1, num2, num3, headtext)
        end
    end
end

function battletext_gettoward(actor, attackerid)
    if attackerid == playerattr_info.actorid then
        return battletext_casttoward.me_to_b
    elseif actor:isme() then
        return battletext_casttoward.a_to_me
    else
        return battletext_casttoward.a_to_b
    end
end

function battletext_getchattype(actor, attacker, attackerid)
    if attackerid == playerattr_info.actorid or playerattr_info.spiritid == attackerid  then
        return chatchanneltype.combatattack
    end
    if attacker ~= nil and attacker:ismyspirit() then
        return chatchanneltype.combatattack
    end
    if actor:isme() or actor:ismyspirit() then
        return chatchanneltype.combathurt
    end
    if actoridisplayer(attackerid) and playerpal_getmatefromplayerid(attackerid) ~= nil then
        return chatchanneltype.combatteamattack
    end
    if actor:isplayer() and actor:isteam() then
        return chatchanneltype.combatteamhurt
    end
    if actoridisplayer(attackerid) and attacker ~= nil and attacker:isenemy() then
        return chatchanneltype.combatplayerattack
    end
    if actor:isplayer() and actor:isenemy() then
        return chatchanneltype.combatplayerhurt
    end
    if not actoridisplayer(attackerid) then
        return chatchanneltype.combatnpcattack
    end
    return nil
end
